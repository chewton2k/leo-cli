const CONCEALMENT_TYPES: [&str; 3] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];

pub struct ProviderIvars {
    state: Arc<Mutex<TxState>>,
    text: String,
}

define_class!(
    #[unsafe(super(NSObject))]
    #[name = "LeoPasteProvider"]
    #[ivars = ProviderIvars]
    pub struct LeoPasteProvider;

    impl LeoPasteProvider {
        #[unsafe(method(pasteboard:provideDataForType:))]
        fn pasteboard_provide_data_for_type(&self, pasteboard: &NSPasteboard, data_type: &NSString) {
            let ivars = self.ivars();
            let is_text = unsafe { data_type.isEqualToString(NSPasteboardTypeString) };
            if is_text {
                if let Ok(mut state) = ivars.state.lock() {
                    state.record_receipt(Instant::now());
                }
            }
            let payload = if is_text {
                NSString::from_str(&ivars.text)
            } else {
                NSString::from_str("")
            };
            let _ = pasteboard.setString_forType(&payload, data_type);
        }

        #[unsafe(method(pasteboardChangedOwner:))]
        fn pasteboard_changed_owner(&self, _pasteboard: &NSPasteboard) {
            if let Ok(mut state) = self.ivars().state.lock() {
                state.ownership_lost = true;
            }
        }
    }
);

impl LeoPasteProvider {
    fn new(state: Arc<Mutex<TxState>>, text: String) -> Retained<Self> {
        let this = Self::alloc().set_ivars(ProviderIvars { state, text });
        unsafe { msg_send![super(this), init] }
    }
}

struct MacPending {
    state: Arc<Mutex<TxState>>,
    activity: Option<leo_core::activity::Lease>,
    current: Arc<dyn Fn() -> bool + Send + Sync>,
    snapshot: super::Snapshot,
    change_count: NSInteger,
    provider: Option<Retained<LeoPasteProvider>>,
    preserve_transcript: bool,
    transcript: String,
    settled: bool,
}

static PENDING: Mutex<Option<Arc<Mutex<MacPending>>>> = Mutex::new(None);

fn settle(pending: &Arc<Mutex<MacPending>>, app_handle: &AppHandle) {
    let mut p = match pending.lock() {
        Ok(p) => p,
        Err(_) => return,
    };
    if p.settled {
        return;
    }
    p.settled = true;

    let activity = p.activity.take();
    let state = p.state.clone();
    let snapshot = std::mem::take(&mut p.snapshot.0);
    let change_count = p.change_count;
    let preserve_transcript = p.preserve_transcript;
    let transcript = p.transcript.clone();
    let provider = p.provider.take();
    drop(p);
    let ownership_lost = state.lock().map(|st| st.ownership_lost).unwrap_or(true);

    let still_ours =
        !ownership_lost && NSPasteboard::generalPasteboard().changeCount() == change_count;
    if !still_ours {
        info!("[reliable-paste] clipboard changed externally; leaving it untouched");
    } else if preserve_transcript {
        let _ = app_handle.clipboard().write_text(&transcript);
        info!("[reliable-paste] left transcript on clipboard as plain text");
    } else {
        let pasteboard = NSPasteboard::generalPasteboard();
        let items: Vec<Retained<objc2::runtime::ProtocolObject<dyn NSPasteboardWriting>>> =
            snapshot
                .iter()
                .map(|formats| {
                    let item = NSPasteboardItem::new();
                    for (kind, bytes) in formats {
                        item.setData_forType(&NSData::with_bytes(bytes), &NSString::from_str(kind));
                    }
                    objc2::runtime::ProtocolObject::from_retained(item)
                })
                .collect();
        if pasteboard.changeCount() != change_count {
            return;
        }
        pasteboard.clearContents();
        pasteboard.writeObjects(&NSArray::from_retained_slice(&items));
        info!("[reliable-paste] restored previous clipboard");
    }

    drop(provider);
    drop(activity);
}

fn flush_pending(app_handle: &AppHandle) {
    let previous = match PENDING.lock() {
        Ok(mut slot) => slot.take(),
        Err(_) => None,
    };
    if let Some(previous) = previous {
        settle(&previous, app_handle);
    }
}

fn spawn_waiter(pending: Arc<Mutex<MacPending>>, app_handle: AppHandle) {
    thread::spawn(move || {
        let outcome = loop {
            thread::sleep(Duration::from_millis(15));
            let (decision, state_snapshot) = {
                let p = match pending.lock() {
                    Ok(p) => p,
                    Err(_) => return,
                };
                if p.settled {
                    return;
                }
                let result = match p.state.lock() {
                    Ok(mut st) => {
                        if !(p.current)() {
                            st.cancelled = true;
                        }
                        let now = Instant::now();
                        let snapshot = (
                            st.any_receipt_after_injection(),
                            st.ownership_lost,
                            st.injection_failed,
                        );
                        (evaluate(&st, now), snapshot)
                    }
                    Err(_) => return,
                };
                result
            };
            if let WaitDecision::Finish = decision {
                break state_snapshot;
            }
        };

        let (receipt_seen, ownership_lost, injection_failed) = outcome;
        if ownership_lost {
            info!("[reliable-paste] settling: clipboard ownership lost");
        } else if receipt_seen {
            info!("[reliable-paste] settling: reads went quiet");
        } else if injection_failed {
            info!("[reliable-paste] settling: chord injection failed, restoring quickly");
        } else {
            info!("[reliable-paste] settling: no read within timeout, restoring anyway");
        }

        let pending_for_finish = pending.clone();
        let app_for_finish = app_handle.clone();
        let _ = app_handle.run_on_main_thread(move || {
            settle(&pending_for_finish, &app_for_finish);
            if let Ok(mut slot) = PENDING.lock() {
                let is_us = slot
                    .as_ref()
                    .map(|current| Arc::ptr_eq(current, &pending))
                    .unwrap_or(false);
                if is_us {
                    *slot = None;
                }
            }
        });
    });
}

pub(super) fn run(
    text: &str,
    app_handle: &AppHandle,
    enigo: &mut enigo::Enigo,
    current: Arc<dyn Fn() -> bool + Send + Sync>,
) -> Result<(), String> {
    let paste_method = &PasteMethod::CtrlV;
    let clipboard_handling = ClipboardHandling::Restore;

    flush_pending(app_handle);
    let activity = leo_core::activity::global()
        .begin()
        .map_err(|e| e.to_string())?;

    let pasteboard = NSPasteboard::generalPasteboard();
    let before = pasteboard.changeCount();
    let mut items = Vec::new();
    let mut bytes = 0usize;
    if let Some(all) = pasteboard.pasteboardItems() {
        if all.len() > 256 {
            return Err(
                "The clipboard has too many items to preserve. Copy them elsewhere first.".into(),
            );
        }
        for item in all {
            let types = item.types();
            if types.len() > 256 {
                return Err("The clipboard has too many formats to preserve.".into());
            }
            let mut formats = Vec::new();
            for kind in types {
                let data = item.dataForType(&kind).ok_or(
                    "A clipboard format could not be preserved. Copy its contents elsewhere first.",
                )?;
                bytes = bytes.saturating_add(data.len());
                if bytes > 64 * 1024 * 1024 {
                    return Err("The clipboard is too large to preserve. Copy its contents elsewhere first.".into());
                }
                formats.push((kind.to_string(), data.to_vec()));
            }
            items.push(formats);
        }
    }
    let snapshot = super::Snapshot::new(items)?;
    if pasteboard.changeCount() != before {
        return Err("The clipboard changed while preparing to paste. Try again.".into());
    }

    if !current() {
        return Err("Dictation cancelled.".into());
    }
    let state = Arc::new(Mutex::new(TxState::new()));
    let provider = LeoPasteProvider::new(state.clone(), text.to_string());
    let pasteboard = NSPasteboard::generalPasteboard();

    let mut types: Vec<Retained<NSString>> = Vec::with_capacity(1 + CONCEALMENT_TYPES.len());
    types.push(NSString::from_str("public.utf8-plain-text"));
    for t in CONCEALMENT_TYPES {
        types.push(NSString::from_str(t));
    }
    let types = NSArray::from_retained_slice(&types);

    let change_count: NSInteger =
        unsafe { msg_send![&*pasteboard, declareTypes: &*types, owner: &*provider] };
    if change_count <= 0 {
        return Err("declareTypes:owner: failed".to_string());
    }
    info!("[reliable-paste] published transcript as lazy promise (changeCount {change_count})");

    if let Ok(mut st) = state.lock() {
        st.injected_at = Some(Instant::now());
    }
    match send_chord(enigo, paste_method) {
        Ok(()) => {
            info!("[reliable-paste] paste chord sent ({paste_method:?})");
        }
        Err(e) => {
            if let Ok(mut st) = state.lock() {
                st.injection_failed = true;
            }
            error!("[reliable-paste] failed to send paste chord: {e}");
        }
    }

    let pending = Arc::new(Mutex::new(MacPending {
        state,
        activity: Some(activity),
        current,
        snapshot,
        change_count,
        provider: Some(provider),
        preserve_transcript: clipboard_handling == ClipboardHandling::CopyToClipboard,
        transcript: text.to_string(),
        settled: false,
    }));
    if let Ok(mut slot) = PENDING.lock() {
        *slot = Some(pending.clone());
    }
    spawn_waiter(pending, app_handle.clone());

    Ok(())
}
